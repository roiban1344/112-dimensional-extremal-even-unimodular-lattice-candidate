"""S9. The Hermitian and O_K-structures on R (paper §7.8; Table D2 [C26]). Not used in the proof of Theorem A.
S9. R のエルミート構造と O_K-構造（論文 §7.8。表 D2 の [C26]）。定理 A の証明には使わない。

  (1) End_A(V) (A = Aut(R)) is 2-dimensional; it contains J with J^2 = -29, J integral on R and
      skew-adjoint (J G_R = -(J G_R)^T); End_A(R) = End_A(V) ∩ End(R) = Z[J] = Z[sqrt -29].
      End_A(V) は 2 次元で、J^2 = -29、R 上で整数、反随伴（J G_R = -(J G_R)^T）な J を含む。End_A(R) = Z[J] = Z[√-29]。
  (2) The centre of C_A(S) contains i with i^2 = -1. The ring End(R) ∩ Q<1, i, J, iJ> is the maximal
      order O_K of K = Q(i, sqrt 29) (index 1; K has class number 3), so O_K acts on R.
      C_A(S) の中心は i^2 = -1 の i を含む。End(R) ∩ Q<1, i, J, iJ> は K = Q(i, √29) の極大整環 O_K（指数 1。K の類数は 3）で、
      O_K が R に作用する。
  (3) The Q-algebra E generated by C_A(S) and J has dimension 16 (= M_2(K)); Lambda = E ∩ End(R) has
      Z-rank 16 and reduced-trace discriminant |d_K|^4, so Lambda is a maximal order of M_2(K)
      (Morita: R = P tensor_{O_K} M with P of rank 2). No idempotent of trace 56 has
      tr(x x*) <= 56 (the search for a short splitting idempotent finds none).
      C_A(S) と J が生成する Q-代数 E は 16 次元（= M_2(K)）。Lambda = E ∩ End(R) は Z-階数 16 で、被約トレースの判別式は |d_K|^4。
      よって Lambda は M_2(K) の極大整環（森田同値: R = P ⊗_{O_K} M、P は階数 2）。tr(x x*) ≤ 56 となる跡 56 の冪等元は無い。

Requires SageMath. Run time: about 3 minutes. / SageMath が要る。実行時間: 約 3 分。
Run / 実行:  sage -python code/supplementary/automorphisms/endomorphisms.py
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", ".."))
from common import Setup, commutant_in_end_S  # noqa: E402
from r112.report import Report  # noqa: E402


def integral_part(mats):
    """Z-basis (as matrices) of { sum y_k M_k : y in Q^k } ∩ M_112(Z): the dual of the Z-span of the
    coefficient rows. / { Σ y_k M_k } ∩ M_112(Z) の Z-基底（行列として）。係数の行の Z-スパンの双対。"""
    from sage.all import QQ, ZZ, lcm, matrix
    k = len(mats)
    rows = list({tuple(col) for col in zip(*[M.list() for M in mats])})
    rows = [r for r in rows if any(r)]
    d = lcm([QQ(x).denominator() for r in rows for x in r])
    span = matrix(ZZ, 0, k)
    for i in range(0, len(rows), 300):
        span = span.stack(matrix(ZZ, [[int(d * x) for x in r] for r in rows[i:i + 300]])).hermite_form(include_zero_rows=False)
    H = (span.change_ring(QQ) / d).inverse().transpose()
    out = [sum(c * M for c, M in zip(row, mats)) for row in H.rows()]
    assert all(x in ZZ for M in out for x in M.list())
    return out, H


def main():
    from sage.all import QQ, ZZ, NumberField, PolynomialRing, identity_matrix, lcm, matrix, pari
    ap = argparse.ArgumentParser(description="S9: Hermitian and O_K-structures on R")
    ap.add_argument("--data", default=None)
    ap.add_argument("--certificates", default=None)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    rep = Report("s9_endomorphisms", a.out)
    st = Setup(a.data, a.certificates)
    cent = st.centralizer()
    X, _ = st.outer_automorphism()
    I2 = identity_matrix(QQ, 112)

    # (1) J. / (1) J。
    KA, gens32 = commutant_in_end_S(st, cent + [X])
    rep.check("(1) dim End_A(V) = 2", KA.nrows() == 2)
    Ys = [sum(c * g for c, g in zip(row, gens32)) for row in KA.rows()]
    Y = next(Y for Y in Ys if Y.minimal_polynomial().degree() == 2)
    J = Y + Y.minimal_polynomial()[1] / 2 * I2                    # trace-free part / トレースが 0 の部分
    assert J * J == (J * J)[0, 0] * I2
    J = J * (QQ(-29) / (J * J)[0, 0]).sqrt()
    rep.check("(1) J^2 = -29 and J is integral on R", J * J == -29 * I2 and all(x in ZZ for x in J.list()))
    rep.check("(1) J is skew-adjoint: J G_R = -(J G_R)^T", J * st.GR == -(J * st.GR).transpose())
    _, H = integral_part([I2, J])
    rep.value("(1) Z-basis of End_A(R) in coordinates (1, J)", [list(r) for r in H.rows()])
    rep.check("(1) End_A(R) = Z[J] = Z[sqrt -29]", abs(H.det()) == 1)

    # (2) O_K. / (2) O_K。
    i_el = [M for M in cent if M * M == -identity_matrix(ZZ, 112) and all(M * c == c * M for c in cent)]
    rep.check("(2) the centre of C_A(S) contains i with i^2 = -1", len(i_el) > 0)
    i = i_el[0].change_ring(QQ)
    rep.check("(2) i commutes with J", i * J == J * i)
    basis = [I2, i, J, i * J]
    _, H = integral_part(basis)
    R_ = PolynomialRing(QQ, "x")
    x = R_.gen()
    K = NumberField([x ** 2 + 1, x ** 2 + 29], "a,b")
    ka, kb = K.gens()
    els = [r[0] + r[1] * ka + r[2] * kb + r[3] * ka * kb for r in H.rows()]
    O = K.order(els)
    rep.value("(2) Z-basis of End(R) ∩ Q<1, i, J, iJ> in coordinates (1, i, J, iJ)", [[str(c) for c in r] for r in H.rows()])
    rep.value("(2) index in the maximal order of K = Q(i, sqrt -29) = Q(i, sqrt 29); class number of K",
              [int(O.index_in(K.maximal_order())), int(K.class_number())])
    rep.check("(2) it is the maximal order O_K", O.index_in(K.maximal_order()) == 1)

    # (3) E and Lambda. / (3) E と Lambda。
    span = [M.change_ring(QQ) for M in cent] + [M.change_ring(QQ) * J for M in cent]
    Eb = matrix(QQ, [M.list() for M in span]).row_space().basis_matrix()
    Emats = [matrix(QQ, 112, 112, list(r)) for r in Eb.rows()]
    rep.check("(3) dim_Q E = 16", len(Emats) == 16)
    Lam, _ = integral_part(Emats)
    rep.check("(3) Lambda = E ∩ End(R) has Z-rank 16", len(Lam) == 16)
    # Reduced trace on E = M_2(K): trd(x) = tr_V(x) / 14 (V is the sum of 14 simple E-modules: 112 = 14 x 8).
    # E = M_2(K) 上の被約トレース: trd(x) = tr_V(x)/14（V は 14 個の単純 E-加群の和: 112 = 14 × 8）。
    T = matrix(QQ, 16, 16, lambda p, q: (Lam[p] * Lam[q]).trace() / 14)
    K2 = NumberField([x ** 2 + 1, x ** 2 - 29], "a,b")
    dK = abs(K2.absolute_discriminant())
    rep.value("(3) |det of the reduced-trace form on Lambda|, |d_K|^4", [int(abs(T.det())), int(dK ** 4)])
    rep.check("(3) Lambda is a maximal order of M_2(K) (discriminant |d_K|^4)",
              all(c in ZZ for c in T.list()) and abs(T.det()) == dK ** 4)
    Q = matrix(QQ, 16, 16, lambda p, q: (Lam[p] * st.GR * Lam[q].transpose() * st.GRi).trace())
    Q = (Q + Q.transpose()) / 2
    scale = lcm([c.denominator() for c in Q.list()])
    vecs = pari((Q * scale).change_ring(ZZ)).qfminim(56 * scale, 200000, 0)
    cands = matrix(ZZ, vecs[2]).transpose().rows() if vecs[2].ncols() else []
    idem = 0
    for c in cands:
        e = sum(ci * M for ci, M in zip(c, Lam))
        idem += any(s * s == s and s.trace() == 56 for s in (e, -e, I2 - e, I2 + e))
    rep.value("(3) elements of Lambda with tr(x x*) <= 56, and idempotents of trace 56 among them", [len(cands), idem])
    rep.finish()


if __name__ == "__main__":
    main()
